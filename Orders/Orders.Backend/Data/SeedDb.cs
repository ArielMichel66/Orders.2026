                        new City() { Name = "Resistencia" },
                        new City() { Name = "Fontana" },
                        new City() { Name = "Saenz Peña" }
                    ]
                },
            ]
            });
            _context.Countries.Add(new Country
            {
                Name = "Estados Unidos",
                States = [
                    new State()
                {
                    Name = "Florida",
                    Cities = [
                        new City() { Name = "Orlando" },
                        new City() { Name = "Miami" },
